/**
 * 解析量框回包 —— **数目对不上就回空数组**（= 这一份不要了，见本节 ★★）。
 *
 * @param {string} text 模型回的原文
 * @param {number} expected 必须正好有这么多个（= `markSlots.length`）
 * @returns {{cx:number,cy:number,w:number,h:number}[]} 已按 cx 升序排好；空 = 不可用
 *
 * ★ 逐个字段校验范围：越界的框叠到画面上是一个跑到画面外的矩形，用户看不见它，
 *   却会发现"这个位置怎么拖不上" —— 而那是零报错的。
 * ★ 宽高要求 > 0：模型偶尔吐 `w=0`（把人当成一条线），那种框永远命不中。
 * ★★ **一行长得像框却是坏的，整份就不可信** —— 不是"把坏的挑掉、剩下的接着数"。
 *   只数幸存者的话会漏掉这种情形：模型吐了 3 行、2 行越界，而这个模板恰好只有 1 个
 *   角色位 —— 幸存 1 个、要 1 个，**判过**。可它明明在画面里看见了 3 个人，
 *   那一份框与我们的角色位根本不是同一回事。所以坏行是**否决票**，不是噪声。
 * ★ **不做去重**：两个框重到一起是"它把同一个人数了两遍"的信号，而我们分不清是
 *   哪两个，去重之后数目反而对上了 —— 那是把一个响亮的失败改造成一个安静的错误。
 */
function parseBoxes(text, expected) {
  const want = Math.max(0, Math.floor(Number(expected) || 0));
  if (want <= 0) return [];
  const out = [];
  let bad = 0;
  for (const rawLine of String(text || "").split(/\r?\n/)) {
    // ★ 数字那四组写成 `-?\d+`（**允许负号**）不是笔误：负数是**坏框**，不是噪声。
    //   只认 `\d+` 的话，`2|-5|500|100|800` 连正则都匹配不上，于是被当成"模型闲聊的一行"
    //   静默跳过 —— 而模型多吐一行时（要 5 个吐了 6 行、其中一行带负数），剩下 5 行正好
    //   凑够数目，整份被判过。范围校验在下面把它挡成 bad，才是这条纪律该有的样子。
    const m = rawLine.trim().match(/^(\d+)\s*[|｜]\s*(-?\d+)\s*[|｜]\s*(-?\d+)\s*[|｜]\s*(-?\d+)\s*[|｜]\s*(-?\d+)\s*$/);
    // 不像框的行直接跳过（模型偶尔会加一句"好的，以下是…"）—— 那是噪声，不是坏框
    if (!m) continue;
    const [cx, cy, w, h] = [Number(m[2]), Number(m[3]), Number(m[4]), Number(m[5])];
    if (![cx, cy, w, h].every((v) => Number.isFinite(v) && v >= 0 && v <= 1000) || w <= 0 || h <= 0) {
      bad += 1;
      continue;
    }
    out.push({ cx, cy, w, h });
  }
  if (bad > 0) {
    console.warn(`[blockoutize] 量框：${bad} 行数值不合法（越界或零宽高），整份丢弃（拖拽层不开）`);
    return [];
  }
  if (out.length !== want) {
    console.warn(`[blockoutize] 量框：要 ${want} 个、解析出 ${out.length} 个，整份丢弃（拖拽层不开）`);
    return [];
  }
  // ★ 排序是**我们**做的，不指望模型真按左到右吐：它说"按从左到右"只是提示，
  //   而下标错位的后果是挂错人。排完就与 markSlots 按下标一一对应。
  out.sort((a, b) => a.cx - b.cx);

  // ★★ 最后一道：**相邻两个中心不许挨得太近**（阈值随人数自适应）。
  //
  // ══ 这条判据 2026-08-17 换过一次，两次都是被真实数据逼的 ═══════════════════
  //   第一版判的是「相邻两个中心不许落进对方的框里」。它抓住了真问题（模板
  //   「编号验证-勿用」：要 2 个给 2 个、数目对得上，但第二个框的中心就在第一个框里、
  //   宽只有 71 —— 那是同一个人的胳膊被当成了人）。
  //   但它是拿**站着的**人偶校准的。换成一段**跳舞**的素材（7 个人）立刻误伤：
  //   实测五发里三发被它拒掉，而数字是 `cx 278±66` vs `417±142.5` —— 两个中心相距 139，
  //   只是后者的框特别宽。手臂张开的舞者本来就宽，邻居的中心落进去是常态。
  //   ⇒ 真正的"同一个人被数了两遍"信号**不是重叠，是中心挨得太近**。
  //
  // ★ 阈值 = 平均间距的 1/3（平均间距 = 1000 / 人数）。它随人数自适应：
  //   2 个人时阈值 167（很松也很够），7 个人时 48。拿手上全部真实数据回归过：
  //     · 公园 5 个人偶  189/350/513/684/853  间隔≥161，阈值 67  → 通过 ✓
  //     · 头部编号验证    188/349/521/687/859  间隔≥161，阈值 67  → 通过 ✓
  //     · 编号验证-勿用   472/621（w=71 那个）  间隔 149，阈值 167 → **拒** ✓
  //     · 群舞第 3 发     278/417              间隔 139，阈值 48  → 通过 ✓（旧判据误拒）
  //     · 群舞第 5 发     705/739              间隔  34，阈值 48  → **拒** ✓
  // ⚠ 同样是**整份否决**，不是"把可疑的那个删掉"：删掉之后数目就对不上了，
  //   而"该删哪个"（谁是人、谁是胳膊）只有看着画面的人分得清。
  const minGap = 1000 / Math.max(1, out.length) / 3;
  for (let i = 1; i < out.length; i += 1) {
    const gap = out[i].cx - out[i - 1].cx;
    if (gap < minGap) {
      console.warn(
        `[blockoutize] 量框：第 ${i} 与第 ${i + 1} 个框的中心只差 ${gap.toFixed(0)}` +
          `（${out.length} 个人时至少要差 ${minGap.toFixed(0)}），多半是同一个人被数了两遍，` +
          `整份丢弃（拖拽层不开）`,
      );
      return [];
    }
  }
  return out;
}

